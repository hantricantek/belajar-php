// perkalian
$hasil = $var1 * $var2;
echo $hasil;
echo "\n";

// pembagian
$hasil = $var1 / $var2;
echo $hasil;
echo "\n";

// modulus
$hasil = $var1 % $var2;
echo $hasil;
echo "\n";

